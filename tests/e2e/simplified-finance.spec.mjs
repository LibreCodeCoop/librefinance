test('4K and mobile financial history use full Nextcloud content width without page overflow', async ({page})=>{
  await login(page)
  await makeSpace(page,'personal')
  await goToView(page,'Movimentações')
  await page.getByRole('button',{name:'Registrar'}).click()
  const dialog=page.getByRole('dialog',{name:'Registrar movimentação'})
  await dialog.getByRole('button',{name:/Já aconteceu/}).click()
  await dialog.getByRole('textbox',{name:'Descrição'}).fill('E2E responsive payment')
  await dialog.getByRole('textbox',{name:'Valor'}).fill('7,80')
  await dialog.getByRole('button',{name:'Salvar'}).click()
  await expect(page.getByRole('row',{name:/E2E responsive payment/})).toBeVisible()
  await page.setViewportSize({width:3840,height:2160})
  const wide=await page.evaluate(()=>({
    viewport:document.documentElement.clientWidth,
    workspace:document.querySelector('.lf-workspace')?.getBoundingClientRect().width,
    doc:document.documentElement.scrollWidth,
  }))
  expect(wide.viewport).toBe(3840)
  expect(wide.workspace).toBeGreaterThan(3000)
  expect(wide.doc).toBeLessThanOrEqual(wide.viewport+2)
  await page.setViewportSize({width:390,height:844})
  const mobile=await page.evaluate(()=>({
    viewport:document.documentElement.clientWidth,
    doc:document.documentElement.scrollWidth,
    tableWidth:document.querySelector('.lf-table-scroll')?.scrollWidth,
    tableVisible:document.querySelector('.lf-table-scroll')?.clientWidth,
  }))
  expect(mobile.doc).toBeLessThanOrEqual(mobile.viewport+2)
  expect(mobile.tableWidth).toBeGreaterThan(mobile.tableVisible)
})

test('all sales and purchases share one invoice list with a server-side type filter', async ({page})=>{
  await login(page)
  await makeSpace(page,'organization')
  await goToView(page,'Clientes e fornecedores')
  await page.getByRole('button',{name:'Novo contato'}).click()
  const contact=page.getByRole('dialog',{name:'Novo contato'})
  await contact.getByRole('textbox',{name:'Nome',exact:true}).fill('E2E Invoices Contact')
  await contact.getByRole('button',{name:'Salvar cadastro'}).click()
  await goToView(page,'Faturas')
  await expect(page.locator('#lf-invoices-type-filter')).toHaveCount(0)
  const suffix=Date.now().toString(36).toUpperCase()
  const create=async (kind,number)=>{
    await page.getByRole('button',{name:'Nova fatura'}).click()
    const dialog=page.getByRole('dialog',{name:'Nova fatura'})
    await dialog.getByRole('button',{
      name:kind==='invoice'?/Venda Vou cobrar/:/Compra Vou pagar/,
    }).click()
    await dialog.getByRole('textbox',{name:'Número'}).fill(number)
    await dialog.getByRole('textbox',{name:'País (ISO 2, obrigatório)'}).fill('BR')
    await dialog.locator('#lf-invoice-contact').click()
    await page.getByRole('option').filter({hasText:'E2E Invoices Contact'}).first().click()
    await dialog.getByRole('textbox',{name:'Descrição da linha 1'}).fill('E2E '+kind)
    await dialog.getByRole('textbox',{name:'Preço unitário'}).fill('25,00')
    await dialog.getByRole('button',{name:'Salvar rascunho'}).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('row',{name:new RegExp(number)})).toBeVisible()
  }
  const sale='SALE-'+suffix
  const bill='BILL-'+suffix
  await create('invoice',sale)
  await create('bill',bill)
  const salesRow=page.getByRole('row',{name:new RegExp(sale)})
  const purchaseRow=page.getByRole('row',{name:new RegExp(bill)})
  await expect(salesRow).toBeVisible()
  await expect(purchaseRow).toBeVisible()
  const filter=page.locator('#lf-invoices-type-filter')
  await expect(filter).toContainText('Todas')
  await filter.click()
  await page.getByRole('group',{name:'Filtrar faturas por tipo'})
    .getByRole('button',{name:'Vendas'}).click()
  await expect(salesRow).toBeVisible()
  await expect(purchaseRow).toHaveCount(0)
  await filter.click()
  await page.getByRole('group',{name:'Filtrar faturas por tipo'})
    .getByRole('button',{name:'Compras'}).click()
  await expect(salesRow).toHaveCount(0)
  await expect(purchaseRow).toBeVisible()
  // The filter does NOT pre-choose the kind of the next fatura.
  await page.getByRole('button',{name:'Nova fatura'}).click()
  const choose=page.getByRole('dialog',{name:'Nova fatura'})
  await expect(choose.getByRole('button',{name:/Venda Vou cobrar/})).toBeVisible()
  await expect(choose.getByRole('button',{name:/Compra Vou pagar/})).toBeVisible()
  await choose.getByRole('button',{name:'Cancelar'}).click()
  await filter.click()
  await page.getByRole('group',{name:'Filtrar faturas por tipo'})
    .getByRole('button',{name:'Todas'}).click()
  await expect(salesRow).toBeVisible()
  await expect(purchaseRow).toBeVisible()
  await salesRow.getByRole('button',{name:'Detalhes'}).click()
  const details=page.getByRole('dialog',{name:'Detalhes da fatura'})
  await details.getByRole('button',{name:'Confirmar venda'}).click()
  await expect(details.getByRole('button',{name:'Ver conta vinculada'})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(details).toHaveCount(0)
  const status=page.locator('#lf-invoice-status-filter')
  await status.click()
  const filtered=page.waitForResponse(r => {
    const url=new URL(r.url())
    return r.request().method()==='GET' && url.pathname.endsWith('/invoices')
      && url.searchParams.get('status')==='draft'
  })
  await page.getByRole('option',{name:'Rascunho',exact:true}).click()
  expect((await filtered).status()).toBe(200)
  await expect(purchaseRow).toBeVisible()
  await expect(salesRow).toHaveCount(0)
  await status.click()
  await page.getByRole('option',{name:'Todas as situações',exact:true}).click()
  await expect(salesRow).toBeVisible()
  await expect(purchaseRow).toBeVisible()
  const purchaseDetails=page.waitForResponse(r => {
    const url=new URL(r.url())
    return r.request().method()==='GET' && /\/invoices\/\d+$/.test(url.pathname)
  })
  await purchaseRow.getByRole('button',{name:'Detalhes'}).click()
  const purchaseResponse=await purchaseDetails
  expect(purchaseResponse.status()).toBe(200)
  expect((await purchaseResponse.json()).invoice.number).toBe(bill)
  await expect(page.getByRole('dialog',{name:'Detalhes da fatura'})
    .getByRole('heading',{name:bill})).toBeVisible()
})
