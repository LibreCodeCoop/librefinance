test('imported bank evidence never posts twice and vanishes after reconciliation', async ({page}) => {
  await login(page)
  await makeSpace(page,'personal')
  await goToView(page,'Movimentações')
  await page.getByRole('button',{name:'Registrar',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Registrar movimentação'})
  await dialog.getByRole('button',{name:/Já aconteceu/}).click()
  const note='E2E water payment '+Date.now().toString(36)
  await dialog.getByRole('textbox',{name:'Descrição'}).fill(note)
  await dialog.getByRole('textbox',{name:'Valor'}).fill('32,10')
  await dialog.getByRole('button',{name:'Salvar',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  const posted=page.getByRole('row',{name:new RegExp(note)})
  await expect(posted).toHaveCount(1)
  await page.getByRole('button',{name:'Conferir extrato'}).click()
  await expect(page.getByRole('heading',{name:'Extrato da conta'})).toBeVisible()
  await page.getByRole('button',{name:'Importar extrato',exact:true}).click()
  const importing=page.getByRole('dialog',{name:'Importar extrato CSV'})
  await expect(importing).toBeVisible()
  const id='statement-'+Date.now().toString(36)
  await importing.locator('input[type=file]').setInputFiles({
    name:'bank-evidence.csv',mimeType:'text/csv',
    buffer:Buffer.from('id,date,amount,description\n'+id+',2026-11-22,-32.10,E2E bank evidence of water\n'),
  })
  await importing.getByRole('button',{name:'Importar para revisão'}).click()
  await expect(importing).toHaveCount(0)
  await page.getByRole('button',{name:'Voltar às movimentações'}).click()
  await expect(posted).toHaveCount(1)
  const pending=page.getByRole('row',{name:/E2E bank evidence of water/})
  await expect(pending).toContainText('A conferir')
  await pending.getByRole('button',{name:'Conferir',exact:true}).click()
  const reconciliation=page.getByRole('dialog',{name:'Conciliar movimentação'})
  await expect(reconciliation).toBeVisible()
  await reconciliation.locator('#lf-bank-journal').click()
  await page.getByRole('option').filter({hasText:note}).first().click()
  await reconciliation.getByRole('button',{name:'Confirmar conciliação'}).click()
  await expect(reconciliation).toHaveCount(0)
  await page.getByRole('button',{name:'Voltar às movimentações'}).click()
  await expect(page.getByRole('row',{name:/E2E bank evidence of water/})).toHaveCount(0)
  await expect(posted).toHaveCount(1)
})

test('confirmed sale becomes one planned line and partial payment has only the remaining balance', async ({page})=>{
  await login(page)
  await makeSpace(page,'organization')
  await goToView(page,'Clientes e fornecedores')
  await page.getByRole('button',{name:'Novo contato'}).click()
  const contact=page.getByRole('dialog',{name:'Novo contato'})
  await contact.getByRole('textbox',{name:'Nome',exact:true}).fill('E2E Unified Buyer')
  await contact.getByRole('button',{name:'Salvar cadastro'}).click()
  await goToView(page,'Faturas')
  await page.getByRole('button',{name:'Nova venda',exact:true}).click()
  const invoice=page.getByRole('dialog',{name:'Nova venda'})
  const number='E2E-UX-'+Date.now().toString(36).toUpperCase()
  await invoice.getByRole('textbox',{name:'Número'}).fill(number)
  await invoice.getByRole('textbox',{name:'País (ISO 2, obrigatório)'}).fill('BR')
  await invoice.locator('#lf-invoice-contact').click()
  await page.getByRole('option').first().click()
  await invoice.getByRole('textbox',{name:'Descrição da linha 1'}).fill('E2E linked service')
  await invoice.getByRole('textbox',{name:'Preço unitário'}).fill('100,00')
  await invoice.getByRole('button',{name:'Salvar rascunho'}).click()
  const invoiceRow=page.getByRole('row',{name:new RegExp(number,'i')})
  await expect(invoiceRow).toBeVisible()
  await invoiceRow.getByRole('button',{name:'Detalhes'}).click()
  const detail=page.getByRole('dialog',{name:'Detalhes da fatura'})
  await detail.getByRole('button',{name:'Confirmar venda'}).click()
  await expect(detail.getByRole('button',{name:'Ver conta vinculada'})).toBeVisible()
  await page.keyboard.press('Escape')
  await goToView(page,'Movimentações')
  const planned=page.getByRole('row',{name:new RegExp('Invoice '+number,'i')})
  await expect(planned).toHaveCount(1)
  await expect(planned).toContainText('Prevista')
  await expect(planned).toContainText('R$ 100,00')
  await planned.getByRole('button',{name:'Receber'}).click()
  const payment=page.getByRole('dialog',{name:'Registrar recebimento'})
  await expect(payment).toBeVisible()
  await payment.getByRole('textbox',{name:'Valor recebido ou pago'}).fill('40,00')
  await payment.getByRole('button',{name:'Registrar sem duplicar'}).click()
  await expect(payment).toHaveCount(0)
  await expect(planned).toContainText('R$ 60,00')
  const actual=page.getByRole('row',{name:new RegExp('Recebimento da venda '+number,'i')})
  await expect(actual).toHaveCount(1)
  await expect(actual).toContainText('R$ 40,00')
  await expect(actual).toContainText('Realizada')
  await expect(planned).toHaveCount(1)
})

