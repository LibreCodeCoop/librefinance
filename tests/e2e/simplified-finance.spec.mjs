test('4K and mobile financial history use full Nextcloud content width without page overflow', async ({page})=>{
  await login(page)
  await makeSpace(page,'personal')
  await goToView(page,'Movimentações')
  await page.getByRole('button',{name:'Registrar'}).click()
  const dialog=page.getByRole('dialog',{name:'Registrar movimentação'})
  await dialog.getByRole('button',{name:/Já aconteceu/}).click()
  await dialog.getByRole('textbox',{name:'Descrição'}).fill('E2E responsive payment')
  await dialog.getByRole('textbox',{name:'Valor'}).fill('7,80')
  await dialog.getByRole('button',{name:'Salvar'}).click()
  await expect(page.getByRole('row',{name:/E2E responsive payment/})).toBeVisible()
  await page.setViewportSize({width:3840,height:2160})
  const wide=await page.evaluate(()=>({
    viewport:document.documentElement.clientWidth,
    workspace:document.querySelector('.lf-workspace')?.getBoundingClientRect().width,
    doc:document.documentElement.scrollWidth,
  }))
  expect(wide.viewport).toBe(3840)
  expect(wide.workspace).toBeGreaterThan(3000)
  expect(wide.doc).toBeLessThanOrEqual(wide.viewport+2)
  await page.setViewportSize({width:390,height:844})
  const mobile=await page.evaluate(()=>({
    viewport:document.documentElement.clientWidth,
    doc:document.documentElement.scrollWidth,
    tableWidth:document.querySelector('.lf-table-scroll')?.scrollWidth,
    tableVisible:document.querySelector('.lf-table-scroll')?.clientWidth,
  }))
  expect(mobile.doc).toBeLessThanOrEqual(mobile.viewport+2)
  expect(mobile.tableWidth).toBeGreaterThan(mobile.tableVisible)
})
