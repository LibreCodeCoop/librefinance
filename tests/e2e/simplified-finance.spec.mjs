test('simple movement flow: planned and posted in the same activity, no double posting', async ({page}) => {
  await login(page)
  await makeSpace(page,'personal')
  await goToView(page,'Movimentações')
  await expect(page.getByRole('heading',{name:'Movimentações',exact:true})).toBeVisible()
  const nav=page.getByRole('navigation',{name:'Navegação do LibreFinance'})
  for (const label of ['Movimentações','Faturas']) {
    await expect(nav.getByRole('link',{name:label,exact:true})).toHaveCount(1)
  }
  for (const label of ['Vendas','Compras','Extratos e conciliação','A pagar e receber',
    'Contas bancárias e caixa']) {
    await expect(nav.getByRole('link',{name:label,exact:true})).toHaveCount(0)
  }
  await expect(page.getByRole('button',{name:'Registrar',exact:true})).toBeVisible()
  await expect(page.getByRole('note',{name:'Nenhuma movimentação registrada'})).toBeVisible()
  await expect(page.locator('#lf-activity-status')).toHaveCount(0)
  await page.getByRole('button',{name:'Registrar',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Registrar movimentação'})
  await expect(dialog.getByRole('button',{name:/Saída Dinheiro que pago/})).toHaveAttribute('aria-pressed','true')
  await dialog.getByRole('button',{name:/Já aconteceu/}).click()
  await dialog.getByRole('textbox',{name:'Descrição'}).fill('Synthetic electricity paid')
  await dialog.getByRole('textbox',{name:'Valor'}).fill('23,50')
  const postedDate = await dialog.locator('#lf-activity-date').inputValue()
  const laterDate = new Date(Date.parse(postedDate + 'T00:00:00Z') + 7 * 86400000).toISOString().slice(0, 10)
  await dialog.getByRole('button',{name:'Salvar',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  const paid=page.getByRole('row',{name:/Synthetic electricity paid/})
  await expect(paid).toBeVisible()
  await expect(paid).toContainText('Realizada')
  await expect(paid).toContainText('R$ 23,50')
  await page.getByRole('button',{name:'Registrar',exact:true}).click()
  await dialog.getByRole('button',{name:/Entrada Dinheiro que recebo/}).click()
  await dialog.getByRole('button',{name:/Vai acontecer/}).click()
  await dialog.getByRole('textbox',{name:'Descrição'}).fill('Synthetic promised rental')
  await dialog.getByRole('textbox',{name:'Valor'}).fill('60,00')
  await dialog.locator('#lf-activity-due').fill(laterDate)
  await dialog.getByRole('button',{name:'Salvar',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  const expected=page.getByRole('row',{name:/Synthetic promised rental/})
  await expect(expected).toBeVisible()
  await expect(expected).toContainText('Prevista')
  await expect(expected).toContainText('R$ 60,00')
  await expect(paid).toHaveCount(1)
  await expect(page.getByRole('row',{name:/Synthetic promised rental/})).toHaveCount(1)
  await page.locator('#lf-activity-status').click()
  await page.getByRole('group',{name:'Filtrar situação financeira'})
    .getByRole('button',{name:'Realizadas'}).click()
  await expect(paid).toBeVisible()
  await expect(expected).toHaveCount(0)
  await page.getByRole('button',{name:'Limpar filtros'}).click()
  await expect(expected).toBeVisible()
  const from = page.locator('#lf-activity-from')
  const through = page.locator('#lf-activity-through')
  const apply = page.getByRole('button',{name:'Aplicar período',exact:true})
  await from.fill(laterDate)
  await through.fill(postedDate)
  await expect(apply).toBeDisabled()
  await from.fill(postedDate)
  await expect(expected).toBeVisible()
  await apply.click()
  await expect(paid).toBeVisible()
  await expect(expected).toHaveCount(0)
  await through.fill(laterDate)
  await expect(expected).toHaveCount(0)
  await page.getByRole('button',{name:'Limpar filtros'}).click()
  await expect(expected).toBeVisible()
  await expect(paid).toBeVisible()
})
