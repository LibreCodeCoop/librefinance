test('contact and item catalogs preserve real records and unit prices across languages', async ({ page }) => {
  await login(page)
  await makeSpace(page, 'personal')
  const id = new URL(page.url()).searchParams.get('spaceId')
  const url = '/index.php/apps/librefinance/?spaceId=' + id
  await page.goto(url + '&view=contacts&forceLanguage=en')
  const view = page.locator('.lf-view')
  await expect(view.getByRole('heading', { name: 'People and businesses' })).toBeVisible()
  await expect(view.getByRole('button', { name: 'Customize contact fields' })).toBeVisible()
  await view.getByRole('button', { name: 'New contact' }).click()
  const contact = page.getByRole('dialog', { name: 'New contact' })
  await contact.getByRole('textbox', { name: 'Name', exact: true }).fill('Contato sintético locale')
  await contact.getByRole('button', { name: 'Save record' }).click()
  await expect(view.getByRole('row', { name: /Contato sintético locale/ })).toContainText('People I receive money from')
  await page.goto(url + '&view=contacts&forceLanguage=pt_BR')
  await expect(view.getByRole('heading', { name: 'Pessoas e estabelecimentos' })).toBeVisible()
  const row = view.getByRole('row', { name: /Contato sintético locale/ })
  await expect(row).toContainText('De quem recebo')
  await expect(row.getByRole('button', { name: 'Editar Contato sintético locale' })).toBeVisible()

  await page.goto(url + '&view=items&forceLanguage=en')
  await expect(view.getByRole('heading', { name: 'Products and services' })).toBeVisible()
  await view.getByRole('button', { name: 'New product or service' }).click()
  const item = page.getByRole('dialog', { name: 'New product or service' })
  await item.getByRole('textbox', { name: 'Name', exact: true }).fill('Serviço sintético locale')
  await item.getByRole('textbox', { name: 'Code/SKU' }).fill('LOCALE-SKU')
  await item.getByRole('textbox', { name: 'Unit price' }).fill('1234.56')
  const saved = page.waitForResponse(response => response.url().includes('/api/spaces/' + id + '/items')
    && response.request().method() === 'POST' && response.ok())
  await item.getByRole('button', { name: 'Save record' }).click()
  expect((await saved).request().postDataJSON().unitPriceMinor).toBe(123456)
  const itemRow = view.getByRole('row', { name: /LOCALE-SKU/ })
  await expect(itemRow).toContainText('Serviço sintético locale')
  const price = await itemRow.locator('.lf-numeric').innerText()
  await page.goto(url + '&view=items&forceLanguage=pt_BR')
  await expect(view.getByRole('heading', { name: 'Produtos e serviços' })).toBeVisible()
  await expect(itemRow).toContainText('Serviço sintético locale')
  await expect(itemRow.locator('.lf-numeric')).toHaveText(price)
})


test('report templates retain saved filter, columns, name and amounts across languages', async ({ page }) => {
  await login(page)
  await makeSpace(page)
  const id = new URL(page.url()).searchParams.get('spaceId')
  const url = '/index.php/apps/librefinance/?spaceId=' + id + '&view=reports&forceLanguage='
  await page.goto(url + 'en')
  await expect(page.getByRole('heading', { name: 'Reports', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Report catalog' })).toBeVisible()
  await page.getByRole('button', { name: 'New report', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'New report' })
  await editor.getByRole('textbox', { name: 'Report name' }).fill('Ativos sintéticos locale')
  await editor.locator('#lf-saved-report-kind').click()
  await page.getByRole('option', { name: /^Trial b\s*alance$/ }).click()
  await editor.getByText('Accounting code', { exact: true }).click()
  await editor.getByText('Account nature', { exact: true }).click()
  await editor.locator('#lf-saved-report-account-class').click()
  await page.getByRole('option', { name: /^As\s*set$/ }).click()
  const saved = page.waitForResponse(response =>
    response.url().includes('/api/spaces/' + id + '/saved-reports')
    && response.request().method() === 'POST' && response.ok())
  await editor.getByRole('button', { name: 'Save report' }).click()
  const payload = (await saved).request().postDataJSON()
  expect(payload.kind).toBe('trial_balance')
  expect(payload.accountClass).toBe('asset')
  expect(payload.columns).toEqual(['name', 'balanceMinor'])
  expect(payload.through).toMatch(/^\d{4}-\d{2}-\d{2}$/)
  await expect(page.getByRole('heading', { name: 'Ativos sintéticos locale' })).toBeVisible()
  const table = page.locator('.lf-report-preview .lf-data-table')
  await expect(table.locator('thead th')).toHaveText(['Account name', 'Ledger balance'])
  const balances = await table.locator('tbody .lf-numeric').allTextContents()
  expect(balances.length).toBeGreaterThan(0)
  await page.goto(url + 'pt_BR')
  await expect(page.getByRole('heading', { name: 'Relatórios', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Ativos sintéticos locale/ }).click()
  await expect(table.locator('thead th')).toHaveText(['Nome da conta', 'Saldo contábil'])
  await expect(table.locator('tbody .lf-numeric')).toHaveText(balances)
  await expect(page.getByText('Filtrado por natureza: Ativo.')).toBeVisible()
})
