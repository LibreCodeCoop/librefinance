  await dialog.getByRole('textbox', { name: 'Short description' }).fill(memo)
  await dialog.getByRole('textbox', { name: 'Markdown notes' }).fill(notes)
  await expect(dialog.getByText(/Outflow of.*Classification:/)).toBeVisible()
