test('dashboard widgets can be reordered, resized, hidden, and restored after reload', async ({ page }) => {
  await login(page)
  await makeSpace(page)
  await page.getByRole('button', { name: 'Personalizar painel' }).click()
  await expect(page.locator('.lf-widget-slot')).toHaveCount(5)
  await expect(page.locator('.lf-widget-slot').first()).toContainText('Resumo financeiro')
  await page.getByRole('button', { name: 'Mover Resumo financeiro para baixo' }).click()
  await expect(page.locator('.lf-widget-slot').first()).toContainText('Movimento do caixa')
  await page.locator('.lf-widget-slot').first().getByRole('button', { name: 'Largura dupla' }).click()
  await expect(page.locator('.lf-widget-slot').first()).toHaveClass(/lf-widget-slot--wide/)
  await page.locator('.lf-widget-slot').first().getByRole('button', { name: 'Ocultar' }).click()
  await page.getByRole('button', { name: 'Concluir edição' }).click()
  await expect(page.locator('.lf-widget-slot')).toHaveCount(4)
  await page.reload()
  await expect(page.locator('.lf-widget-slot')).toHaveCount(4)
  await expect(page.locator('.lf-widget-slot').first()).toContainText('Saldo de caixa')
  await page.getByRole('button', { name: 'Personalizar painel' }).click()
  await page.getByRole('button', { name: 'Restaurar padrão' }).click()
  await page.getByRole('button', { name: 'Concluir edição' }).click()
  await expect(page.locator('.lf-widget-slot')).toHaveCount(5)
})

