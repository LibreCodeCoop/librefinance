test('company private AppData logo is uploaded, displayed, retrieved and removed in a browser', async ({ page }) => {
  await login(page)
  await makeSpace(page)
  await goToView(page, 'Empresas')
  await page.getByRole('button', { name: 'Cadastrar empresa' }).click()
  const create = page.getByRole('dialog', { name: 'Cadastrar empresa' })
  await create.getByRole('textbox', { name: 'Nome legal' }).fill('Empresa com logo')
  await create.locator('#lf-company-country').click()
  await page.getByRole('option').filter({ hasText: 'Portugal (PT)' }).click()
  await create.getByRole('button', { name: 'Salvar empresa' }).click()
  await expect(page.getByRole('row', { name: /Empresa com logo/ })).toBeVisible()
  await page.getByRole('button', { name: 'Editar Empresa com logo' }).click()
  const edit = page.getByRole('dialog', { name: 'Editar empresa' })
  await edit.locator('input[type="file"]').setInputFiles('tests/e2e/fixtures/logo.png')
  await expect(edit.getByRole('img', { name: 'Logotipo atual da empresa' })).toBeVisible()
  const path = await edit.getByRole('img', { name: 'Logotipo atual da empresa' }).getAttribute('src')
  const response = await page.request.get(path)
  expect(response.status()).toBe(200)
  expect(response.headers()['content-type']).toContain('image/png')
  expect(response.headers()['cache-control']).toContain('private')
  await edit.getByRole('button', { name: 'Remover logotipo' }).click()
  await expect(edit.getByRole('img', { name: 'Logotipo atual da empresa' })).toHaveCount(0)
  const gone = await page.request.get(path)
  expect(gone.status()).toBe(404)
})

