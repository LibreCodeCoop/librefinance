test('a saved trial balance report selects and persists real table columns and a server filter', async ({ page }) => {
  await login(page)
  await makeSpace(page)
  await goToView(page, 'Relatórios')
  await page.getByRole('button', { name: 'Novo relatório', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Novo relatório' })
  await editor.getByRole('textbox', { name: 'Nome do relatório' }).fill('Ativos resumidos')
  await editor.locator('#lf-saved-report-kind').click()
  await page.getByRole('option', { name: 'Balancete', exact: true }).click()
  await editor.getByText('Código contábil', { exact: true }).click()
  await editor.getByText('Natureza', { exact: true }).click()
  await editor.locator('#lf-saved-report-account-class').click()
  await page.getByRole('option', { name: 'Ativo', exact: true }).click()
  await editor.getByRole('button', { name: 'Salvar relatório' }).click()
  await expect(editor).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Ativos resumidos' })).toBeVisible()
  const table = page.locator('.lf-report-preview .lf-data-table')
  await expect(table.locator('thead th')).toHaveCount(2)
  await expect(table.locator('thead th').first()).toHaveText('Nome da conta')
  await expect(table.locator('thead th').last()).toHaveText('Saldo contábil')
  await expect(table.getByRole('row').last()).toContainText('R$ 0,00')
  await expect(page.getByText('Filtrado por natureza: Ativo.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: /Ativos resumidos/ })).toBeVisible()
  await page.getByRole('button', { name: /Ativos resumidos/ }).click()
  await expect(page.locator('.lf-report-preview .lf-data-table thead th')).toHaveCount(2)
  await expect(page.getByText('Filtrado por natureza: Ativo.')).toBeVisible()
  await page.getByRole('button', { name: 'Excluir', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Excluir relatório permanentemente' })
  await confirmation.getByRole('button', { name: 'Excluir configuração' }).click()
  await expect(page.getByRole('button', { name: /Ativos resumidos/ })).toHaveCount(0)
})

